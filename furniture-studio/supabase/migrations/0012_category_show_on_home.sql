-- Категории верхнего уровня можно скрыть с главной («Что мы создаём»), не
-- убирая их из каталога /works. По умолчанию true — существующие категории
-- продолжают показываться как раньше, ничего не отваливается молча после
-- накатывания миграции.
--
-- Поле есть и у подкатегорий (проще схема, отдельный constraint не нужен),
-- но UI (CategoriesManager) показывает переключатель только у категорий
-- верхнего уровня — подкатегория никогда не рендерится как отдельная плитка
-- на главной, только внутри модалки выбора у родителя (см.
-- components/home/CategoryTile.tsx), так что для неё это поле ни на что не
-- влияет и осознанно скрыто, чтобы не вводить в заблуждение.
alter table public.categories
  add column if not exists show_on_home boolean not null default true;

notify pgrst, 'reload schema';
